/// The call screen's labels for one language, with optional per-key overrides.
class TeleStrings {
  const TeleStrings._(this.languageCode, this._map);

  /// Picks a dictionary for a language tag (`bn-BD` uses `bn`; unknown tags use English) and applies
  /// [overrides] on top.
  factory TeleStrings.of(String? language, {Map<TeleStringKey, String>? overrides}) {
    final code = (language ?? 'en').split(RegExp('[-_]')).first.toLowerCase();
    final base = dictionaries[code] ?? _en;
    final lang = dictionaries.containsKey(code) ? code : 'en';
    return TeleStrings._(lang, overrides == null || overrides.isEmpty ? base : {...base, ...overrides});
  }

  static const Map<String, Map<TeleStringKey, String>> dictionaries = {'en': _en, 'bn': _bn};

  final String languageCode;
  final Map<TeleStringKey, String> _map;

  String operator [](TeleStringKey key) => _map[key] ?? _en[key]!;

  /// The label for [key] with `{placeholders}` filled from [vars].
  String format(TeleStringKey key, [Map<String, Object> vars = const {}]) =>
      this[key].replaceAllMapped(RegExp(r'\{(\w+)\}'), (m) => vars.containsKey(m[1]) ? '${vars[m[1]]}' : m[0]!);
}
